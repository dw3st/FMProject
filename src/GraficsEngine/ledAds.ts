/** Board language of a country; a country outside the six languages gets English, an unknown one null. */
export function ledLangOfCountry(country: string | undefined | null): LedLang | null {
  return country ? COUNTRY_LANG[country] ?? "en" : null;
}

/**
 * The home club's board language from its players' nationalities: the most common one decides (a country outside the
 * six languages gets English). Empty list: null (the caller falls back to the game language).
 */
export function ledLangOfNationalities(nats: readonly (string | undefined | null)[]): LedLang | null {
  const count = new Map<string, number>();
  for (const n of nats) if (n) count.set(n, (count.get(n) ?? 0) + 1);
  let best: string | null = null, max = 0;
  for (const [n, c] of count) if (c > max || (c === max && best !== null && n < best)) { best = n; max = c; }
  return ledLangOfCountry(best);
}

export const LED_ADS: readonly { text: Record<LedLang, string>; bg: number; fg: number }[] = NAMES.map((row, i) => {
  const [bg, fg] = PAIRS[(i * 7) % PAIRS.length]!;
  const text = Object.fromEntries(LED_LANGS.map((l, k) => [l, row[k]!])) as Record<LedLang, string>;
  return { text, bg, fg };
});
