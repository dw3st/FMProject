/** The game language as a board language (pt-* → pt, es-* → es…); anything else is English. */
export const ledLang = (language: string | undefined): LedLang => {
  const base = language?.toLowerCase().slice(0, 2) ?? "";
  return (LED_LANGS as readonly string[]).includes(base) ? (base as LedLang) : "en";
};

